<#
.SYNOPSIS
    spec-check 钩子安装器：把结构校验装进当前仓库的 pre-push。

.DESCRIPTION
    写入 .git/hooks/pre-push，推送前先跑 check-spec.ps1，失败即阻止推送。
    如果该钩子已存在且不是本工具写的，会跳过（-Force 覆盖）。
    已存在的其它钩子不会被吞掉：安装的是本工具的钩子，仓库其它钩子请另行合并。

.PARAMETER Repo
    目标仓库，默认当前目录。

.PARAMETER Uninstall
    卸载本工具写的 pre-push。

.PARAMETER Force
    覆盖非本工具写入的同名钩子。
#>
[CmdletBinding()]
param(
    [string]$Repo = (Get-Location).Path,

    [switch]$Uninstall,

    [switch]$Force
)

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false) } catch { }

$marker = 'spec-check hook (generated by install-hook.ps1)'
$checker = Join-Path $PSScriptRoot 'check-spec.ps1'
if (-not (Test-Path -LiteralPath $checker)) {
    Write-Host "找不到 check-spec.ps1（应在 $PSScriptRoot）" -ForegroundColor Red
    exit 1
}

$repoPath = (Resolve-Path -LiteralPath $Repo).Path
# 注意：不能用 --git-path hooks，它会被 core.hooksPath 改写成全局目录
$gitDir = (& git -C $repoPath rev-parse --git-dir 2>$null) -join ''
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($gitDir)) {
    Write-Host "不是 git 仓库：$repoPath" -ForegroundColor Red
    exit 1
}
$hookDir = if ([System.IO.Path]::IsPathRooted($gitDir)) { Join-Path $gitDir 'hooks' } else { Join-Path (Join-Path $repoPath $gitDir) 'hooks' }
$hookPath = Join-Path $hookDir 'pre-push'

function Test-IsOurs {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return $false }
    $head = Get-Content -LiteralPath $Path -TotalCount 3 -ErrorAction SilentlyContinue
    return (($head -join "`n").Contains('spec-check'))
}

if ($Uninstall) {
    if (Test-IsOurs $hookPath) {
        Remove-Item -LiteralPath $hookPath -Force
        Write-Host "已删 $hookPath" -ForegroundColor Yellow
    }
    else { Write-Host '  pre-push 不是本工具装的，跳过' -ForegroundColor DarkGray }
    exit 0
}

if ((Test-Path -LiteralPath $hookPath) -and -not (Test-IsOurs $hookPath) -and -not $Force) {
    Write-Host "  pre-push 已存在且不是本工具装的；确认覆盖请加 -Force" -ForegroundColor Yellow
    exit 1
}

$checkerUnix = $checker -replace '\\', '/'
$hook = @'
#!/bin/sh
# __MARKER__
if command -v pwsh >/dev/null 2>&1; then
  PS=pwsh
  EXTRA=''
elif command -v powershell >/dev/null 2>&1; then
  PS=powershell
  EXTRA='-ExecutionPolicy Bypass'
else
  echo 'spec-check: 未找到 pwsh / powershell，跳过校验' >&2
  exit 0
fi
"$PS" -NoProfile -NonInteractive $EXTRA -File "__CHECKER__"
RC=$?
[ $RC -ne 0 ] && exit $RC
exit 0
'@
$hook = $hook.Replace('__MARKER__', $marker).Replace('__CHECKER__', $checkerUnix) -replace "`r`n", "`n"

[System.IO.File]::WriteAllText($hookPath, $hook, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "  已写 $hookPath" -ForegroundColor Green
Write-Host '完成。撤销：install-hook.ps1 -Uninstall' -ForegroundColor Cyan
exit 0
