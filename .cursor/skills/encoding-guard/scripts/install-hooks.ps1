<#
.SYNOPSIS
    encoding-guard 钩子安装器：把编码校验装进 pre-commit / pre-push。

.DESCRIPTION
    安装后每次提交、每次推送都会先跑 check-encoding.ps1，校验不通过就挡住（退出码 1）。

    两种作用域：
      repo    只装当前仓库的 .git/hooks（默认）
      global  装到 ~/.githooks 并设置 core.hooksPath，对之后所有仓库生效；
              会链式调用仓库自带的同名钩子，不会把它们覆盖掉

    卸载用 -Uninstall；global 会顺带清掉 core.hooksPath（仅当它指向本工具的目录）。

.PARAMETER Scope
    repo | global

.PARAMETER Repo
    repo 作用域下的目标仓库，默认当前目录。

.PARAMETER HooksDir
    global 作用域的钩子目录，默认 ~/.githooks。

.PARAMETER Uninstall
    卸载对应作用域的钩子。

.EXAMPLE
    .\install-hooks.ps1

.EXAMPLE
    .\install-hooks.ps1 -Scope global
#>
[CmdletBinding()]
param(
    [ValidateSet('repo', 'global')]
    [string]$Scope = 'repo',

    [string]$Repo = (Get-Location).Path,

    [string]$HooksDir = '',

    [switch]$Uninstall,

    [switch]$Force
)

$ErrorActionPreference = 'Stop'
try { [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false) } catch { }

$marker = 'encoding-guard hook (generated by install-hooks.ps1)'
$checker = Join-Path $PSScriptRoot 'check-encoding.ps1'
if (-not (Test-Path -LiteralPath $checker)) {
    Write-Host "找不到 check-encoding.ps1（应在 $PSScriptRoot）" -ForegroundColor Red
    exit 1
}

function Get-HookTemplate {
    param([string]$HookName, [string]$CheckerPath, [string]$HookDir, [switch]$Chain)

    $chainBlock = ''
    if ($Chain) {
        $chainBlock = @'
LOCAL_HOOK="$(git rev-parse --git-dir)/hooks/__HOOKNAME__"
if [ -f "$LOCAL_HOOK" ] && [ "$LOCAL_HOOK" != "__HOOKFILE__" ]; then
  sh "$LOCAL_HOOK" "$@" || exit $?
fi
'@
    }

    $tpl = @'
#!/bin/sh
# __MARKER__
if command -v pwsh >/dev/null 2>&1; then
  PS=pwsh
  EXTRA=''
elif command -v powershell >/dev/null 2>&1; then
  PS=powershell
  EXTRA='-ExecutionPolicy Bypass'
else
  echo 'encoding-guard: 未找到 pwsh / powershell，跳过校验' >&2
  exit 0
fi
"$PS" -NoProfile -NonInteractive $EXTRA -File "__CHECKER__" -Mode __CHECKMODE__
RC=$?
__CHAIN__
[ $RC -ne 0 ] && exit $RC
exit 0
'@

    $hookMode = if ($HookName -eq 'pre-commit') { 'commit' } else { 'push' }
    $path = Join-Path $HookDir $HookName
    # 链式块里的占位符必须在插入模板前替换，否则会留下 __HOOKNAME__ / __HOOKFILE__
    $chainBlock = $chainBlock.Replace('__HOOKNAME__', $HookName).Replace('__HOOKFILE__', ($path -replace '\\', '/'))
    $text = $tpl.Replace('__MARKER__', $marker).
        Replace('__CHECKER__', ($CheckerPath -replace '\\', '/')).
        Replace('__HOOKNAME__', $HookName).
        Replace('__CHECKMODE__', $hookMode).
        Replace('__HOOKFILE__', ($path -replace '\\', '/')).
        Replace('__CHAIN__', $chainBlock.TrimEnd())
    return $text
}

function Write-HookFile {
    param([string]$Dir, [string]$Hook, [string]$Text)
    $path = Join-Path $Dir $Hook
    $lf = $Text -replace "`r`n", "`n"
    [System.IO.File]::WriteAllText($path, $lf, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "  已写 $path" -ForegroundColor Green
}

function Test-IsOurs {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return $false }
    $head = Get-Content -LiteralPath $Path -TotalCount 3 -ErrorAction SilentlyContinue
    return (($head -join "`n").Contains('encoding-guard'))
}

if ($Scope -eq 'repo') {
    $repoPath = (Resolve-Path -LiteralPath $Repo).Path
    # 注意：不能用 --git-path hooks，它会被 core.hooksPath 改写成全局目录
    $gitDir = (& git -C $repoPath rev-parse --git-dir 2>$null) -join ''
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($gitDir)) {
        Write-Host "不是 git 仓库：$repoPath" -ForegroundColor Red
        exit 1
    }
    $hookDir = if ([System.IO.Path]::IsPathRooted($gitDir)) { Join-Path $gitDir 'hooks' } else { Join-Path (Join-Path $repoPath $gitDir) 'hooks' }

    Write-Host "作用域 repo：$repoPath" -ForegroundColor Cyan

    if ($Uninstall) {
        foreach ($h in 'pre-commit', 'pre-push') {
            $p = Join-Path $hookDir $h
            if (Test-IsOurs $p) { Remove-Item -LiteralPath $p -Force; Write-Host "  已删 $p" -ForegroundColor Yellow }
            else { Write-Host "  跳过 $h（不是本工具装的）" -ForegroundColor DarkGray }
        }
        exit 0
    }

    foreach ($h in 'pre-commit', 'pre-push') {
        $p = Join-Path $hookDir $h
        if ((Test-Path -LiteralPath $p) -and -not (Test-IsOurs $p) -and -not $Force) {
            Write-Host "  $h 已存在且不是本工具装的，跳过；确认覆盖请加 -Force" -ForegroundColor Yellow
            continue
        }
        Write-HookFile -Dir $hookDir -Hook $h -Text (Get-HookTemplate -HookName $h -CheckerPath $checker -HookDir $hookDir)
    }
    Write-Host '完成。撤销：install-hooks.ps1 -Uninstall' -ForegroundColor Cyan
    exit 0
}

# ---- global ----
if ([string]::IsNullOrWhiteSpace($HooksDir)) { $HooksDir = Join-Path $HOME '.githooks' }
$HooksDir = [System.IO.Path]::GetFullPath($HooksDir)
Write-Host "作用域 global：$HooksDir" -ForegroundColor Cyan

if ($Uninstall) {
    foreach ($h in 'pre-commit', 'pre-push') {
        $p = Join-Path $HooksDir $h
        if (Test-IsOurs $p) { Remove-Item -LiteralPath $p -Force; Write-Host "  已删 $p" -ForegroundColor Yellow }
    }
    $current = (& git config --global --get core.hooksPath 2>$null) -join ''
    if ($current -and ($current -replace '/', '\') -eq ($HooksDir -replace '/', '\')) {
        & git config --global --unset core.hooksPath
        Write-Host '  已清 core.hooksPath' -ForegroundColor Yellow
    }
    exit 0
}

$existing = (& git config --global --get core.hooksPath 2>$null) -join ''
if ($existing -and (($existing -replace '/', '\') -ne ($HooksDir -replace '/', '\')) -and -not $Force) {
    Write-Host "core.hooksPath 已指向 $existing，跳过；确认覆盖请加 -Force" -ForegroundColor Yellow
    exit 1
}

$guardDir = Join-Path $HooksDir 'encoding-guard'
New-Item -ItemType Directory -Path $guardDir -Force | Out-Null
$target = Join-Path $guardDir 'check-encoding.ps1'
Copy-Item -LiteralPath $checker -Destination $target -Force
Write-Host "  已复制校验脚本到 $target" -ForegroundColor Green

foreach ($h in 'pre-commit', 'pre-push') {
    Write-HookFile -Dir $HooksDir -Hook $h -Text (Get-HookTemplate -HookName $h -CheckerPath $target -HookDir $HooksDir -Chain)
}

& git config --global core.hooksPath ($HooksDir -replace '\\', '/')
Write-Host "  已设置 core.hooksPath = $HooksDir" -ForegroundColor Green
Write-Host '完成。撤销：install-hooks.ps1 -Scope global -Uninstall' -ForegroundColor Cyan
exit 0
